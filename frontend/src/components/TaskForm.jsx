import { useState, useEffect } from 'react';
import { useNavigate, useParams } from 'react-router-dom';
import { createTask, updateTask, getTaskById, generateTaskDescription } from '../api/taskApi';
import { useToast } from '../context/ToastContext';
import './TaskForm.css';
import './TaskModal.css';

/**
 * TaskForm — Handles both Create and Edit modes for tasks with Intelligent AI Assistant.
 * In edit mode, pre-fills the form with existing task data fetched by ID.
 * Features:
 * - Intelligent AI Title Understanding (Path A: Clarification vs Path B: Direct Generation)
 * - Multi-turn Q&A context synthesis
 * - Clean UI with clarification cards and answer inputs
 */
export default function TaskForm() {
  const navigate = useNavigate();
  const { id } = useParams();
  const isEditMode = Boolean(id);
  const { addToast } = useToast();

  const [formData, setFormData] = useState({
    title: '',
    description: '',
    status: 'pending',
    priority: 'medium',
    dueDate: '',
  });
  const [loading, setLoading] = useState(false);
  const [fetchLoading, setFetchLoading] = useState(isEditMode);
  const [error, setError] = useState(null);

  // Intelligent AI State
  const [aiLoading, setAiLoading] = useState(false);
  const [aiFeedback, setAiFeedback] = useState(null); // { type: 'success' | 'error' | 'info', message: '' }
  const [aiStatus, setAiStatus] = useState('idle'); // 'idle' | 'clarification' | 'ready'
  const [clarificationQuestions, setClarificationQuestions] = useState([]);
  const [clarificationAnswers, setClarificationAnswers] = useState({});

  /**
   * Initial AI Request: sends title to Gemini for intelligent understanding
   */
  const handleGenerateDescription = async () => {
    const title = formData.title.trim();

    if (!title) {
      setAiFeedback({
        type: 'error',
        message: '⚠️ Please enter a task title first so the AI knows what to generate.',
      });
      document.getElementById('title')?.focus();
      return;
    }

    setAiLoading(true);
    setAiFeedback(null);

    const result = await generateTaskDescription(title);
    setAiLoading(false);

    if (!result.success) {
      setAiFeedback({
        type: 'error',
        message: result.message || 'AI generation failed. Please enter the description manually.',
      });
      return;
    }

    // PATH A: Unclear / Non-meaningful title -> Ask dynamic clarification questions
    if (result.status === 'needs_clarification' && Array.isArray(result.questions) && result.questions.length > 0) {
      setAiStatus('clarification');
      setClarificationQuestions(result.questions);
      setClarificationAnswers({});
      setAiFeedback({
        type: 'info',
        message: `ℹ️ The title "${title}" needs clarification. Please answer these quick questions so the AI can understand your task:`,
      });
      return;
    }

    // PATH B: Clear and meaningful title -> Direct generation immediately
    if (result.description) {
      setFormData((prev) => ({
        ...prev,
        description: result.description,
      }));
      setAiStatus('ready');
      setAiFeedback({
        type: 'success',
        message: '✓ Actionable description generated by AI! Review and edit before saving.',
      });
    }
  };

  /**
   * Submit answers to clarification questions
   */
  const handleClarificationSubmit = async (e) => {
    e.preventDefault();
    const title = formData.title.trim();

    const answersPayload = clarificationQuestions.map((q, idx) => ({
      question: q,
      answer: (clarificationAnswers[idx] || '').trim(),
    }));

    setAiLoading(true);
    setAiFeedback(null);

    const result = await generateTaskDescription(title, { answers: answersPayload });
    setAiLoading(false);

    if (result.success && result.description) {
      setFormData((prev) => ({
        ...prev,
        description: result.description,
      }));
      setAiStatus('ready');
      setClarificationQuestions([]);
      setClarificationAnswers({});
      setAiFeedback({
        type: 'success',
        message: '✓ Meaningful description generated from your answers! Review or edit below before saving.',
      });
    } else {
      setAiFeedback({
        type: 'error',
        message: result.message || 'Failed to synthesize description. Please enter description manually.',
      });
    }
  };

  const handleAnswerChange = (index, value) => {
    setClarificationAnswers((prev) => ({
      ...prev,
      [index]: value,
    }));
  };

  // Fetch existing task data in edit mode
  useEffect(() => {
    if (!isEditMode) return;

    const fetchTask = async () => {
      setFetchLoading(true);
      const result = await getTaskById(id);
      if (result.success) {
        const task = result.data;
        setFormData({
          title: task.title || '',
          description: task.description || '',
          status: task.status || 'pending',
          priority: task.priority || 'medium',
          dueDate: task.dueDate ? task.dueDate.split('T')[0] : '',
        });
      } else {
        setError(result.error);
        addToast(`Failed to load task: ${result.error}`, 'error');
      }
      setFetchLoading(false);
    };

    fetchTask();
  }, [id, isEditMode, addToast]);

  const handleTitleChange = (e) => {
    const newTitle = e.target.value;
    setFormData((prev) => ({ ...prev, title: newTitle }));

    // Reset clarification state if user changes the title
    if (aiStatus === 'clarification') {
      setAiStatus('idle');
      setClarificationQuestions([]);
      setClarificationAnswers({});
      setAiFeedback(null);
    }
  };

  const handleChange = (e) => {
    const { name, value } = e.target;
    setFormData((prev) => ({ ...prev, [name]: value }));
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setLoading(true);
    setError(null);

    // Build payload — only include dueDate if set
    const payload = { ...formData };
    if (!payload.dueDate) delete payload.dueDate;

    const result = isEditMode
      ? await updateTask(id, payload)
      : await createTask(payload);

    setLoading(false);

    if (result.success) {
      addToast(
        isEditMode ? 'Task updated successfully!' : 'Task created successfully!',
        'success'
      );
      navigate('/');
    } else {
      setError(result.error);
      addToast(result.error, 'error');
    }
  };

  if (fetchLoading) {
    return (
      <div className="form-container">
        <div className="form-card">
          <div className="form-skeleton">
            <div className="skeleton-line skeleton-line--title" />
            <div className="skeleton-line" />
            <div className="skeleton-line" />
            <div className="skeleton-line skeleton-line--short" />
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="form-container">
      <div className="form-card">
        <div className="form-header">
          <h2 className="form-title">
            {isEditMode ? '✏️ Edit Task' : '✨ Create New Task'}
          </h2>
          <p className="form-subtitle">
            {isEditMode
              ? 'Update the task details below'
              : 'Fill in the details to add a new task'}
          </p>
        </div>

        {error && (
          <div className="form-error" role="alert">
            <span className="form-error__icon">⚠</span>
            {error}
          </div>
        )}

        <form onSubmit={handleSubmit} className="task-form" id="task-form">
          <div className="form-group">
            <label htmlFor="title" className="form-label">Title</label>
            <input
              type="text"
              id="title"
              name="title"
              value={formData.title}
              onChange={handleTitleChange}
              placeholder="e.g. Prepare React Practical 11 Docker deployment"
              required
              className="form-input"
              autoFocus
            />
          </div>

          <div className="form-group">
            <div className="modal-label-row" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '6px' }}>
              <label htmlFor="description" className="form-label" style={{ margin: 0 }}>Description</label>
              <button
                type="button"
                className="btn-ai-generate"
                onClick={handleGenerateDescription}
                disabled={aiLoading}
                id="btn-generate-ai-description-page"
              >
                {aiLoading && aiStatus !== 'clarification' ? (
                  <>
                    <span className="spinner" style={{ width: '12px', height: '12px' }}></span>
                    Analyzing title...
                  </>
                ) : (
                  <>✨ Generate description with AI</>
                )}
              </button>
            </div>

            {/* AI Feedback Banner */}
            {aiFeedback && (
              <div
                className={`ai-banner ${
                  aiFeedback.type === 'success'
                    ? 'ai-banner--success'
                    : aiFeedback.type === 'info'
                    ? 'ai-banner--info'
                    : 'ai-banner--error'
                }`}
                style={{ marginBottom: '10px' }}
                role="alert"
              >
                <span className="ai-banner__icon">
                  {aiFeedback.type === 'success' ? '✓' : aiFeedback.type === 'info' ? 'ℹ' : '⚠'}
                </span>
                <span className="ai-banner__text">{aiFeedback.message}</span>
              </div>
            )}

            {/* PATH A: Dynamic Clarification Questions Card */}
            {aiStatus === 'clarification' && clarificationQuestions.length > 0 && (
              <div className="ai-clarification-card" id="ai-clarification-panel-page" style={{ marginBottom: '12px' }}>
                <div className="ai-clarification-card__header">
                  <div className="ai-clarification-card__title">
                    <span>🤖</span>
                    <strong>Help AI Understand Your Goal</strong>
                    <span className="ai-clarification-badge">Clarification Needed</span>
                  </div>
                  <button
                    type="button"
                    className="ai-clarification-card__close"
                    onClick={() => setAiStatus('idle')}
                    title="Dismiss questions and write description manually"
                  >
                    &times;
                  </button>
                </div>

                <p className="ai-clarification-card__intro">
                  The title <strong>"{formData.title}"</strong> needs more context. Answer these {clarificationQuestions.length} quick questions so the AI can generate an accurate description:
                </p>

                <div className="ai-clarification-questions-list">
                  {clarificationQuestions.map((question, idx) => (
                    <div key={idx} className="ai-clarification-q-item">
                      <label className="ai-clarification-q-label">
                        <span className="ai-q-number">{idx + 1}</span>
                        <span className="ai-q-text">{question}</span>
                      </label>
                      <input
                        type="text"
                        className="ai-clarification-input"
                        value={clarificationAnswers[idx] || ''}
                        onChange={(e) => handleAnswerChange(idx, e.target.value)}
                        placeholder="Your answer..."
                        disabled={aiLoading}
                      />
                    </div>
                  ))}
                </div>

                <div className="ai-clarification-actions">
                  <button
                    type="button"
                    className="btn-ai-submit-answers"
                    onClick={handleClarificationSubmit}
                    disabled={aiLoading}
                  >
                    {aiLoading ? (
                      <>
                        <span className="spinner" style={{ width: '12px', height: '12px' }}></span>
                        Generating Description...
                      </>
                    ) : (
                      '✨ Generate My Description'
                    )}
                  </button>
                  <button
                    type="button"
                    className="btn-ai-cancel-clarification"
                    onClick={() => setAiStatus('idle')}
                    disabled={aiLoading}
                  >
                    Cancel
                  </button>
                </div>
              </div>
            )}

            <textarea
              id="description"
              name="description"
              value={formData.description}
              onChange={handleChange}
              placeholder="Enter description manually or generate automatically with AI..."
              required
              className="form-input form-textarea"
              rows={4}
            />

            <div className="ai-disclaimer" style={{ fontSize: '0.8rem', color: '#64748b', marginTop: '4px', display: 'flex', alignItems: 'center', gap: '6px' }}>
              <span>ⓘ</span>
              <span>
                AI-generated suggestion: Review and edit this content before saving. AI-generated content may be inaccurate.
              </span>
            </div>
          </div>

          <div className="form-row">
            <div className="form-group">
              <label htmlFor="status" className="form-label">Status</label>
              <select
                id="status"
                name="status"
                value={formData.status}
                onChange={handleChange}
                className="form-input form-select"
              >
                <option value="pending">🟡 Pending</option>
                <option value="in-progress">🔵 In Progress</option>
                <option value="completed">🟢 Completed</option>
              </select>
            </div>

            <div className="form-group">
              <label htmlFor="priority" className="form-label">Priority</label>
              <select
                id="priority"
                name="priority"
                value={formData.priority}
                onChange={handleChange}
                className="form-input form-select"
              >
                <option value="low">Low</option>
                <option value="medium">Medium</option>
                <option value="high">High</option>
              </select>
            </div>

            <div className="form-group">
              <label htmlFor="dueDate" className="form-label">Due Date</label>
              <input
                type="date"
                id="dueDate"
                name="dueDate"
                value={formData.dueDate}
                onChange={handleChange}
                className="form-input"
              />
            </div>
          </div>

          <div className="form-actions">
            <button
              type="button"
              className="btn btn--secondary"
              onClick={() => navigate('/')}
              id="form-cancel-btn"
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn btn--primary"
              disabled={loading}
              id="form-submit-btn"
            >
              {loading ? (
                <span className="btn-loading">
                  <span className="spinner" />
                  {isEditMode ? 'Updating...' : 'Creating...'}
                </span>
              ) : (
                isEditMode ? 'Update Task' : 'Create Task'
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
